"""Export the FastAPI OpenAPI schema and generated frontend route constants.

Usage:
    uv run python -m scripts.export_openapi
    uv run python -m scripts.export_openapi --check
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any

OPENAPI_OUTPUT = Path("frontend/src/api/generated/openapi.json")
ROUTES_OUTPUT = Path("frontend/src/api/generated/paths.ts")

_DEFAULT_ENV = {
    "APP_ENV": "test",
    "LOG_LEVEL": "WARNING",
    "ANTHROPIC_API_KEY": "test-key",
    "DATABASE_URL": "postgresql+asyncpg://test:test@localhost/test",
    "REDIS_URL": "redis://localhost:6379",
    "CHAT_API_KEY": "test-chat-api-key",
    "TELEGRAM_BOT_TOKEN": "123456:test-token",
    "TELEGRAM_ALLOWED_USER_IDS": "123456",
    "TELEGRAM_WEBHOOK_URL": "https://test.example.com",
    "TELEGRAM_WEBHOOK_SECRET": "test-webhook-secret",
}


def ensure_env_defaults() -> None:
    """Set the minimum environment required to import the app."""
    for key, value in _DEFAULT_ENV.items():
        os.environ.setdefault(key, value)


def path_to_key(path: str) -> str:
    """Convert an API path like `/api/chat/stream` into `apiChatStream`."""
    parts: list[str] = []
    for segment in path.strip("/").split("/"):
        if not segment:
            continue
        if segment.startswith("{") and segment.endswith("}"):
            name = segment[1:-1]
            parts.append(f"by_{name}")
            continue
        normalized = segment.replace("-", "_").replace(".", "_").replace(":", "_")
        parts.append(normalized)

    if not parts:
        return "root"

    key = parts[0].lower()
    for part in parts[1:]:
        if part.startswith("by_"):
            key += "By" + part[3:].title().replace("_", "")
        else:
            key += part.title().replace("_", "")
    return key


def build_openapi_schema() -> dict[str, Any]:
    """Import the FastAPI app and return its OpenAPI schema."""
    ensure_env_defaults()
    from src.app.main import app

    return app.openapi()


def build_routes_ts(schema: dict[str, Any]) -> str:
    """Render a generated TypeScript file containing route constants."""
    lines = [
        "// This file is auto-generated by scripts/export_openapi.py.",
        "// Do not edit by hand.",
        "",
        "export const API_PATHS = {",
    ]

    for path in sorted(schema.get("paths", {})):
        lines.append(f'  {path_to_key(path)}: "{path}",')

    lines.extend(
        [
            "} as const;",
            "",
            "export type ApiPath = (typeof API_PATHS)[keyof typeof API_PATHS];",
            "",
        ]
    )
    return "\n".join(lines)


def write_outputs(schema: dict[str, Any]) -> None:
    """Write the generated OpenAPI contract files to disk."""
    OPENAPI_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OPENAPI_OUTPUT.write_text(
        json.dumps(schema, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    ROUTES_OUTPUT.write_text(build_routes_ts(schema), encoding="utf-8")


def check_outputs(schema: dict[str, Any]) -> bool:
    """Return True when checked-in generated files match current schema."""
    openapi_text = json.dumps(schema, indent=2, sort_keys=True) + "\n"
    routes_text = build_routes_ts(schema)

    current_openapi = (
        OPENAPI_OUTPUT.read_text(encoding="utf-8") if OPENAPI_OUTPUT.exists() else None
    )
    current_routes = ROUTES_OUTPUT.read_text(encoding="utf-8") if ROUTES_OUTPUT.exists() else None

    ok = True
    if current_openapi != openapi_text:
        print(f"OpenAPI snapshot drift detected in {OPENAPI_OUTPUT}")
        ok = False
    if current_routes != routes_text:
        print(f"Generated route drift detected in {ROUTES_OUTPUT}")
        ok = False
    return ok


def main() -> None:
    """CLI entry point."""
    parser = argparse.ArgumentParser(
        description="Export generated OpenAPI contract files for the frontend",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if generated files are out of date instead of writing them",
    )
    args = parser.parse_args()

    schema = build_openapi_schema()

    if args.check:
        if not check_outputs(schema):
            sys.exit(1)
        print("OpenAPI contract files are up to date")
        return

    write_outputs(schema)
    print(f"Wrote {OPENAPI_OUTPUT} and {ROUTES_OUTPUT}")


if __name__ == "__main__":
    main()
